import dotenv from "dotenv";
dotenv.config();
import mysql from "mysql2/promise";
import { drizzle } from "drizzle-orm/mysql2";
import { eq } from "drizzle-orm";
import { users } from "../drizzle/schema.ts";

let dbUrl = process.env.DATABASE_URL;
if ((dbUrl.startsWith("'") && dbUrl.endsWith("'")) || (dbUrl.startsWith('"') && dbUrl.endsWith('"'))) {
  dbUrl = dbUrl.slice(1, -1);
}

const pool = mysql.createPool({ uri: dbUrl });
const db = drizzle(pool);

try {
  const query = db.select().from(users).where(eq(users.email, "abdalla.shaban.hafez@gmail.com")).limit(1);
  console.log("SQL generated by Drizzle:", query.toSQL());
  console.log("Testing db.select().from(users).where(eq(users.email, '...')).limit(1):");
  const res = await query;
  console.log("Success with limit(1):", res);
} catch (e) {
  console.error("Failed with limit(1):", e);
}

try {
  console.log("Testing db.select().from(users).where(eq(users.email, '...')) without limit:");
  const res2 = await db.select().from(users).where(eq(users.email, "abdalla.shaban.hafez@gmail.com"));
  console.log("Success without limit:", res2);
} catch (e) {
  console.error("Failed without limit:", e);
}

await pool.end();
